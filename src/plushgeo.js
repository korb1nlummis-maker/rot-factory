const _m = new THREE.Matrix4(), _q = new THREE.Quaternion(), _e = new THREE.Euler(), _s = new THREE.Vector3(), _p = new THREE.Vector3();

function ell(lod, sx, sy, sz, px, py, pz, tint = [1, 1, 1], rot = [0, 0, 0], opts = {}) {
  const small = Math.max(sx, sy, sz) < 0.085;
  const eye = opts.eye;
  if (lod === 0 && small && !eye) return null;
  const ws = lod === 1 ? (small ? 8 : 14) : small ? 4 : 7;
  const hs = lod === 1 ? (small ? 6 : 10) : small ? 3 : 5;
  const g = new THREE.SphereGeometry(1, ws, hs);
  _e.set(rot[0], rot[1], rot[2]);
  _q.setFromEuler(_e);
  _s.set(sx, sy, sz);
  _p.set(px, py, pz);
  _m.compose(_p, _q, _s);
  g.applyMatrix4(_m);
  g.deleteAttribute('uv');
  const n = g.attributes.position.count;
  const col = new Float32Array(n * 3);
  for (let i = 0; i < n; i++) { col[i * 3] = tint[0]; col[i * 3 + 1] = tint[1]; col[i * 3 + 2] = tint[2]; }
  g.setAttribute('color', new THREE.BufferAttribute(col, 3));
  return g;
}

function eyes(lod, y, z, sep = 0.1, r = 0.04) {
  return [
    ell(lod, r, r * 1.2, r * 0.8, -sep, y, z, DARK, [0, 0, 0], { eye: true }),
    ell(lod, r, r * 1.2, r * 0.8, sep, y, z, DARK, [0, 0, 0], { eye: true }),
  ];
}
function cheeks(lod, y, z, sep = 0.16) {
  return [
    ell(lod, 0.055, 0.03, 0.02, -sep, y, z, PINK),
    ell(lod, 0.055, 0.03, 0.02, sep, y, z, PINK),
  ];
}

// a ring or arc (torus) piece, for the shapes that need one; `order` is the Euler order of rot
function tor(lod, R, r, px, py, pz, tint = [1, 1, 1], rot = [0, 0, 0], arc = Math.PI * 2, order = 'XYZ') {
  const g = new THREE.TorusGeometry(R, r, lod === 1 ? 8 : 5, lod === 1 ? 24 : 10, arc);
  _e.set(rot[0], rot[1], rot[2], order);
  _q.setFromEuler(_e);
  _s.set(1, 1, 1);
  _p.set(px, py, pz);
  _m.compose(_p, _q, _s);
  g.applyMatrix4(_m);
  g.deleteAttribute('uv');
  const n = g.attributes.position.count;
  const col = new Float32Array(n * 3);
  for (let i = 0; i < n; i++) { col[i * 3] = tint[0]; col[i * 3 + 1] = tint[1]; col[i * 3 + 2] = tint[2]; }
  g.setAttribute('color', new THREE.BufferAttribute(col, 3));
  return g;
}

// a hard-edged block piece (houses and the like)
function box(w, h, d, px, py, pz, tint = [1, 1, 1], rot = [0, 0, 0]) {
  const g = new THREE.BoxGeometry(w, h, d);
  _e.set(rot[0], rot[1], rot[2]);
  _q.setFromEuler(_e);
  _s.set(1, 1, 1);
  _p.set(px, py, pz);
  _m.compose(_p, _q, _s);
  g.applyMatrix4(_m);
  g.deleteAttribute('uv');
  const n = g.attributes.position.count;
  const col = new Float32Array(n * 3);
  for (let i = 0; i < n; i++) { col[i * 3] = tint[0]; col[i * 3 + 1] = tint[1]; col[i * 3 + 2] = tint[2]; }
  g.setAttribute('color', new THREE.BufferAttribute(col, 3));
  return g;
}

const _v1 = new THREE.Vector3(), _up = new THREE.Vector3(0, 1, 0);
// a rounded rod from point a to point b (legs and the like)
function limb(lod, ax, ay, az, bx, by, bz, r, tint = [1, 1, 1]) {
  _v1.set(bx - ax, by - ay, bz - az);
  const len = _v1.length();
  _v1.divideScalar(len);
  _q.setFromUnitVectors(_up, _v1);
  _e.setFromQuaternion(_q, 'XYZ');
  return ell(lod, r, len / 2 + r * 0.6, r, (ax + bx) / 2, (ay + by) / 2, (az + bz) / 2, tint, [_e.x, _e.y, _e.z]);
}

